/** Generate runtime resources from the two approved, committed PNG families. */
import { join } from "node:path";
const root = join(import.meta.dir, "../../..");
const asset = (variant: string, size: number) => Bun.file(join(root, "assets/brand", variant, "icon-" + size + ".png"));
// Compatibility exports and installed application icons default to color.
for (const size of [1024, 512, 192, 180, 32]) {
  await Bun.write(join(root, "assets/brand/icon-" + size + ".png"), asset("color", size));
}
await Bun.write(join(root, "apps/desktop/build/icon.png"), asset("color", 1024));
await Bun.write(join(root, "apps/desktop/assets/brand-icon.png"), asset("color", 192));
let source = "// Generated by apps/desktop/scripts/gen-icon.ts. Do not edit.\n";
let client = "// Generated brand images for offline and standalone UI.\n";
const images: Record<string, Record<string, Record<number, string>>> = {};
for (const variant of ["color", "blue"]) {
  for (const size of [192, 512, 180, 32]) {
    const data = Buffer.from(await asset(variant, size).arrayBuffer()).toString("base64");
    const name = variant.toUpperCase() + "_ICON_" + size;
    const line = "export const " + name + " = " + JSON.stringify(data) + ";\n";
    source += line;
  }
}
for (const variant of ["color", "blue"]) {
  images[variant] = {};
  for (const tone of ["light", "dark"]) {
    images[variant]![tone] = {};
    for (const size of [192, 32]) {
      images[variant]![tone]![size] = Buffer.from(await asset(variant + "/" + tone, size).arrayBuffer()).toString("base64");
    }
  }
}
const frames = await Bun.file(join(root, "assets/brand/frames.json")).json();
client += "export const BRAND_FRAMES = " + JSON.stringify(frames) + " as const;\n";
client += "export const BRAND_IMAGES = " + JSON.stringify(images) + " as const;\n";
for (const size of [192, 512, 180, 32]) source += "export const ICON_" + size + " = COLOR_ICON_" + size + ";\n";
await Bun.write(join(root, "src/webui/server/icons.ts"), source);
await Bun.write(join(root, "src/webui/brand-images.ts"), client);
console.log("Updated color defaults and preserved blue brand assets.");
